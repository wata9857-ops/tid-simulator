/* 線路図に入ってから吹田タ (北方貨物線の着発線の位置) に着くまでのシミュレーターの所要 [分]。
   実測 (tools/harness.js --seed=20260922、以前の乱数の貨物列車の中央値。始発の出発準備5分を含む)。
   シミュレーターの貨物列車は実物より遅い (待避・乗務員交代の停車を含む) ので、実際の時刻表の所要ではなく
   実測の値で逆算し、吹田タでの時刻が時刻表に合うようにする。 */
const FREIGHT_LEAD = {
    "米原":   { "吹田タ": 134, "京都タ": 78 },
    "敦賀":   { "吹田タ": 150, "京都タ": 95 },     // 湖西線経由
    "上郡":   { "吹田タ": 192 },
    "姫路タ": { "吹田タ": 151 },
    "神戸タ": { "吹田タ": 117 },
    "京都タ": { "吹田タ": 60 }
};
/* 時間帯による所要の増減 [分]。上の値は1日の中央値で、実測すると
   昼間 (10〜22時) は旅客列車に詰まって遅く、夜中 (22〜6時) は線路が空いて早く着いた
   (tools/check_freight_timetable.js で測って決めた。夜中は貨物列車どうしが続くので、減らしすぎない)。
   吹田タの時刻 (分) で決める。線路図の端から入る列車 (米原・敦賀・上郡) だけに使う。 */
function frtLeadAdj(anchorMin, from) {
    if (FREIGHT_TERMINALS[from]) return 0;
    const h = Math.floor(anchorMin / 60) % 24;
    if (h >= 22 || h < 6) return -10;
    if (h < 10) return 5;
    return 25;
}
const FREIGHT_START_PREP = 300;          // 始発の出発準備 (Train の waiting_start の 300秒)
const FREIGHT_SPLIT_DWELL = 30;          // 吹田タにこれ以上 [分] 止まる通過列車は、着と発の2本に分ける
const FREIGHT_CLAIM_WINDOW = 4 * 3600;   // ターミナルに着いた列車が受け持てる、そこ始発の列車の発車まで

/** "0026" → 26 (分)。時刻が無ければ null */
function frtHm(s) {
    const m = /(\d{2})(\d{2})/.exec(s || "");
    return m ? parseInt(m[1], 10) * 60 + parseInt(m[2], 10) : null;
}
/** 吹田の欄 → { arr, dep } (分) */
function frtSuitaTimes(cell) {
    const c = cell || "";
    const ts = (c.match(/\d{4}/g) || []).map(frtHm);
    if (!ts.length) return { arr: null, dep: null };
    if (ts.length >= 2) return { arr: ts[0], dep: ts[1] };
    if (/着/.test(c)) return { arr: ts[0], dep: null };
    if (/発/.test(c)) return { arr: null, dep: ts[0] };
    return { arr: ts[0], dep: ts[0] };                  // 通過・短い停車
}

/**
 * 時刻表の1行を、線路図の中を走る列車 (区間) に直す。
 * 戻り値: 区間の配列 (線路図に出てこない列車は空)。
 *   { id, no, dir, from, dest, realFrom, realTo, anchor [秒, 0時から], lead [秒], link, claimable, loco }
 */
function freightTimetableLegs() {
    const legs = [];
    const has = (c) => /\d{4}/.test(c || "");
    const place = (s) => (s || "").split(" ")[0];
    [[FREIGHT_TT_DOWN, -1], [FREIGHT_TT_UP, 1]].forEach(([rows, dir]) => {
        rows.forEach(r => {
            const [no, loco, ume, osk, sui, kud, aji, kob, fromS, toS, note] = r;
            if (/^[a-z]/.test(no)) return;                      // h・t 印 (単機・線路図の外だけを走る)
            const originCell = dir === -1 ? ume : kob;
            const destCell = dir === -1 ? kob : ume;
            const realFrom = place(fromS), realTo = place(toS);
            const T51 = /^T51/.test(loco);
            const S = frtSuitaTimes(sui);
            // ---- 線路図に入る所
            let from, anchor = null, lead = 0, claimable = false;
            let dest = null;
            if (dir === 1 && /発/.test(ume)) {
                from = "京都タ";                                 // 京都貨物 始発の上り (8480 京都貨→稲沢)
                anchor = frtHm(ume); lead = FREIGHT_START_PREP; claimable = true;
            } else if (has(originCell) && /発/.test(originCell)) {
                from = dir === -1 ? "京都タ" : "神戸タ";         // 京都貨物・神戸タ 始発
                anchor = frtHm(originCell); lead = FREIGHT_START_PREP; claimable = true;
            } else if (has(originCell) && /着/.test(originCell)) {
                // 京都貨物で終着 (8481 稲沢→京都貨)
                from = T51 ? "敦賀" : "米原"; dest = "京都タ";
                anchor = frtHm(originCell); lead = FREIGHT_LEAD[from]["京都タ"] * 60;
            } else if (has(originCell)) {
                if (dir === -1) from = T51 ? "敦賀" : "米原";
                else from = (realFrom === "姫路貨") ? "姫路タ" : "上郡";
            } else {
                from = "吹田タ";                                 // 吹田タ始発、大阪タ・百済タ・安治川口から
                claimable = /^吹田/.test(realFrom);
            }
            // ---- 行先
            if (!dest) {
                if (has(destCell) && /着/.test(destCell)) dest = dir === -1 ? "神戸タ" : "京都タ";
                else if (has(destCell)) {
                    if (dir === -1) dest = (realTo === "姫路貨") ? "姫路タ" : realTo;
                    else dest = T51 ? "富山タ" : (["名古屋タ", "稲沢"].indexOf(realTo) >= 0 ? "名古屋タ" : "東京タ");
                }
                else if (/着/.test(osk)) dest = "大阪タ";
                else if (/着/.test(kud)) dest = "百済タ";
                else if (/着/.test(aji)) dest = "安治川タ";
                else if (/着/.test(sui)) dest = "吹田タ";
            }
            if (!dest) return;
            // 吹田タと線路図の外のあいだだけを走る列車は、線路図の本線に出てこない
            if (from === "吹田タ" && (dest === "吹田タ" || FREIGHT_EXIT_VIA_SUITA.indexOf(dest) >= 0)) return;
            // ---- 時刻を合わせる所
            let anchorAt = "origin";
            if (from === "姫路タ") claimable = true;
            if (from === "吹田タ") { anchor = S.dep !== null ? S.dep : S.arr; lead = FREIGHT_START_PREP; anchorAt = "suita"; }
            else if (S.arr !== null && FREIGHT_LEAD[from]) {
                // 吹田タに時刻のある列車は、吹田タの時刻に合わせる (始発駅の時刻より、吹田での時刻を優先する)
                anchor = S.arr; lead = (FREIGHT_LEAD[from]["吹田タ"] + frtLeadAdj(S.arr, from)) * 60; anchorAt = "suita";
            } else if (anchor === null && from === "姫路タ") { anchor = frtHm(fromS); lead = FREIGHT_START_PREP; }
            else if (anchor !== null && lead > FREIGHT_START_PREP) anchorAt = "kyoto";
            if (anchor === null) return;
            const base = { no: no, dir: dir, loco: loco, realFrom: realFrom, realTo: realTo, note: note, anchorAt: anchorAt,
                           suitaArr: S.arr, suitaDep: S.dep };
            const through = from !== "吹田タ" && dest !== "吹田タ" && FREIGHT_EXIT_VIA_SUITA.indexOf(dest) < 0 &&
                            !FREIGHT_TERMINALS[from] && S.arr !== null && S.dep !== null;
            let dwell = S.dep - S.arr; if (dwell < 0) dwell += 1440;
            if (through && dwell >= FREIGHT_SPLIT_DWELL) {
                // 吹田タで長く止まる: 着と発の2本に分け、着いた列車がそのまま発車する
                const a = Object.assign({}, base, { id: no + "a", from: from, dest: "吹田タ", anchor: anchor * 60, lead: lead, kind: "arr" });
                let dep = S.dep; if (dep < S.arr) dep += 1440;
                const b = Object.assign({}, base, { id: no + "b", from: "吹田タ", dest: dest, anchor: dep * 60,
                                                    lead: FREIGHT_START_PREP, kind: "dep", link: a.id });
                legs.push(a, b);
                return;
            }
            legs.push(Object.assign({}, base, { id: no, from: from, dest: dest, anchor: anchor * 60, lead: lead,
                                                kind: from === "吹田タ" || FREIGHT_TERMINALS[from] ? "dep" : "arr",
                                                claimable: claimable }));
        });
    });
    return legs;
}

/* ------------------------------------------------------------------ 毎日の運転 */

/** その日の区間の列 (時刻のばらつき・遅れをここで決める) */
Spawner.prototype.buildFreightDay = function (day) {
    const F = this.frt;
    if (!F.legs) F.legs = freightTimetableLegs();
    const base = day * 86400;
    F.legs.forEach(L => {
        let jitter = (Math.random() * 2 - 1) * 180;                 // ±3分
        if (Math.random() < 0.10) jitter += 300 + Math.random() * 1200;   // 1割は 5〜25分遅れ
        const depAt = base + L.anchor + jitter;                        // 吹田タ (など) の時刻
        F.queue.push({ key: L.id + "@" + day, leg: L, day: day, spawnAt: depAt - L.lead, depAt: depAt,
                       state: "pending", train: null });
    });
    F.queue.sort((a, b) => a.spawnAt - b.spawnAt);
};

/**
 * 時刻表の貨物列車を出す。夜中も走らせる (旅客列車の生成を止める時間でも呼ぶ)。
 */
Spawner.prototype.checkFreightSchedule = function (ct) {
    if (!this.frt) {
        this.frt = { queue: [], lastDay: -1, stats: { spawned: 0, claimed: 0, missed: 0, late: 0, ended: 0 } };
    }
    const F = this.frt;
    // その日の列を、始まる8時間前 (前の晩に線路図へ入る列車のぶん) に作る
    while ((F.lastDay + 1) * 86400 - 8 * 3600 <= ct) {
        F.lastDay++;
        this.buildFreightDay(F.lastDay);
        // 立ち上げのとき、もう過ぎている列車は走らせない
        F.queue.forEach(e => { if (e.state === "pending" && e.spawnAt < ct - 120 && !F.started) e.state = "skipped"; });
    }
    F.started = true;
    for (const e of F.queue) {
        if (e.spawnAt > ct) break;
        if (e.state !== "pending") continue;
        if (e.nextTry && ct < e.nextTry) continue;
        // 着いた列車がそのまま発車する区間は、その列車が走っているあいだは出さない (着いたら受け持つ)
        if (e.leg.link) {
            const a = F.queue.find(x => x.day === e.day && x.leg.id === e.leg.link);
            if (a && a.state === "spawned" && a.train && a.train.state !== "finished" && ct < e.spawnAt + 3 * 3600) continue;
        }
        if (ct > e.spawnAt + 3600) { e.state = "missed"; F.stats.missed++; continue; }
        const ok = this.trySpawn("貨物", e.leg.dir, null, e);
        if (ok) {
            e.state = "spawned"; F.stats.spawned++;
            if (ct > e.spawnAt + 300) F.stats.late++;
            const t = this.game.trains[this.game.trains.length - 1];
            if (t && t.trainNo === e.leg.no) {
                e.train = t;
                t.frtKey = e.key;
                t.realOrigin = e.leg.realFrom; t.realDest = e.leg.realTo;
                t.frtPlanned = e.depAt;
            }
        } else {
            e.nextTry = ct + 45;                                  // 線路が空くまで少し待つ (遅れて発車する)
        }
    }
    // 古いものを捨てる
    if (F.queue.length > 600) F.queue = F.queue.filter(e => e.spawnAt > ct - 12 * 3600);
};

/**
 * 貨物ターミナルに着いた列車が受け持つ、そこ始発の時刻表の列車を探す。
 *   1. 同じ列車の「吹田タ発」の区間 (吹田タで長く止まる通過列車)
 *   2. そのターミナル始発の列車 (FREIGHT_CLAIM_WINDOW 以内に発車するもの)
 * 見つからなければ null (荷役のあと運用を終える)。
 */
Spawner.prototype.claimFreightDeparture = function (train, key) {
    const F = this.frt;
    if (!F) return null;
    const now = this.game.currentTime;
    let best = null;
    const mine = train.frtKey ? F.queue.find(e => e.key === train.frtKey) : null;
    if (mine) {
        best = F.queue.find(e => e.state === "pending" && e.day === mine.day && e.leg.link === mine.leg.id);
    }
    if (!best) {
        for (const e of F.queue) {
            if (e.state !== "pending" || e.leg.from !== key || !e.leg.claimable) continue;
            const leave = e.spawnAt + FREIGHT_START_PREP;          // そのターミナルを出る時刻
            if (leave < now + 1200 || leave > now + FREIGHT_CLAIM_WINDOW) continue;
            if (!best || leave < best.spawnAt + FREIGHT_START_PREP) best = e;
        }
    }
    if (!best) return null;
    best.state = "claimed"; best.train = train;
    F.stats.claimed++;
    return best;
};
