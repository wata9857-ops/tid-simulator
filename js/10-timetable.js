/** その線・向き・種別の、いまの時間帯の1時間あたり本数 */
function ttPerHour(line, dirName, type, h) {
    const L = TIMETABLE[line];
    if (!L) return 0;
    const D = L[dirName];
    if (!D) return 0;
    const arr = D[type];
    if (!arr) return 0;
    const pid = ttPeriod(h);
    const i = TT_PERIODS.findIndex(p => p.id === pid);
    return (i >= 0 && arr[i] !== undefined) ? arr[i] : 0;
}

/**
 * 次の発車時刻を、実際の時刻表と同じ「毎時同じ分」に決める。
 *
 * 乱数で間隔を決めると、たまたま続けて2本出たり10分空いたりして
 * 列車が固まる (団子運転になる)。実際のダイヤは
 *   普通  :00 :15 :30 :45
 *   快速  :07 :22 :37 :52
 * のように毎時同じ分の繰り返しなので、同じ形にする。
 *
 *   perHour … 1時間あたりの本数
 *   phase   … 毎時の何秒目から始めるか (種別ごとにずらして続行を避ける)
 */
function ttNextTime(ct, perHour, phase) {
    if (!perHour || perHour <= 0) return Infinity;
    const step = 3600 / perHour;
    const hourStart = Math.floor(ct / 3600) * 3600;
    let t = hourStart + (phase % step);
    while (t <= ct) t += step;
    return t;
}

/* 種別ごとの発車分のずらし方 (秒)。
   実際の時刻表も 普通 :00、快速 :07、新快速 :02 のようにずれている。
   同じ分に重ねると、続行間隔が足りなくて発車できない列車が出る。 */
const TT_PHASE = {
    "普通":   0,
    "快速":   420,    // :07
    "新快速": 120,    // :02
    "特急":   600,    // :10
    "貨物":   900,
    "回送":   1500
};

/** その種別の発車分のずらし (向きでも少しずらす) */
function ttPhase(type, dirName) {
    return (TT_PHASE[type] || 0) + (dirName === "Down" ? 210 : 0);
}

/* ------------------------------------------------------------------ 在線本数の目安

   ■ なぜ必要か
     列車は終着駅で折り返して次の列車になるので、種別を変えずに
     いつまでも走り続ける。生成だけを時刻表に合わせても、
     朝にできた「普通ばかり」の偏りが折り返しで一日中残ってしまう。

     実際に測ると、昼間の本線の在線は
       普通 153本 / 快速 23本 / 新快速 26本 / 特急 12本
     だった。時刻表から計算した必要数は
       普通  8本/時 × 片道約1.3時間 × 上下 ＝ 約21本 (西明石〜京都)
             ＋ 琵琶湖線・北陸線ぶん          ＝ 約70本
       快速  6本/時 × 約1.5時間 × 上下        ＝ 約26本
       新快速 8本/時 × 約2.0時間 × 上下       ＝ 約30本
     なので、普通だけが2倍以上あり、内側線 (電車線) が普通で埋まって
     快速・新快速が発車できない状態になっていた。

   ■ どう使うか
     この本数を超えているときは
       ・新しく作らない            (js/08-spawner-mainline.js trySpawn)
       ・終着駅で折り返さず車両所へ戻す (js/27-operations.js preferTurnback)
     ようにする。列車を消すのではなく、運用を終えて入区させるだけ。
*/
const TT_ACTIVE_BUDGET = {
    /* 普通 … 8本/時 × 西明石〜京都 片道約1.9時間 × 上下 ＝ 約30本
              ＋ 琵琶湖線・北陸線・姫路口ぶん ＝ 約50本
       快速 … 6本/時 × 約1.6時間 × 上下 ＝ 約20本 (+姫路口) ＝ 28本
       新快速 8本/時 × 約2.0時間 × 上下 ＝ 約32本
       回送 … 実際の回送は多くないので少なめに抑える */
    main:   { "普通": 42, "快速": 28, "新快速": 34, "特急": 18, "貨物": 20, "回送": 14 },
    branch: { "普通": 30, "快速": 16, "回送": 6 }
};

/** その列車が分岐線 (湖西・宝塚・東西) にいるか */
function ttIsBranch(t) {
    return t.trackId.indexOf("Kosei") === 0 ||
           t.trackId.indexOf("Fukuchi") === 0 ||
           t.trackId.indexOf("Tozai") === 0;
}

/** いま走っている本数 (線区・種別ごと) */
function ttActiveCount(game, line, type) {
    let n = 0;
    for (const t of game.trains) {
        if (t.state === "finished" || t.state === "in_depot") continue;
        if (t.type !== type) continue;
        if ((ttIsBranch(t) ? "branch" : "main") !== line) continue;
        n++;
    }
    return n;
}

/** その種別が在線本数の目安を超えているか */
function ttOverBudget(game, line, type) {
    const b = (TT_ACTIVE_BUDGET[line] || {})[type];
    if (b === undefined) return false;
    return ttActiveCount(game, line, type) >= b;
}

/**
 * その種別が走りすぎているとき、終着駅で運用を終える確率。
 *
 * 折り返しは種別を変えないので、何もしないと朝にできた偏り
 * (普通ばかり) が一日中残り、内側線が普通で埋まる。
 * いっぽう「超えていたら必ず入区」にすると、京都に着いた列車が
 * すべて向日町操へ回送されてしまい、琵琶湖線の普通がゼロになる。
 * そこで、超えているぶんに応じた割合だけ運用を終えるようにして、
 * どの区間も列車が途切れないまま本数が落ち着くようにする。
 */
function ttRetireChance(game, line, type) {
    const b = (TT_ACTIVE_BUDGET[line] || {})[type];
    if (!b) return 0;
    const n = ttActiveCount(game, line, type);
    if (n <= b) return 0;
    return Math.min(0.85, (n - b) / b * 4.0);
}
