/** その種類の場面の、時間の倍率の重みつき平均 (場所・時刻の条件は見ない) */
const _scenMeanCache = {};
function incidentScenarioMeanDur(type) {
    if (_scenMeanCache[type.id]) return _scenMeanCache[type.id];
    const list = INCIDENT_SCENARIOS[type.id] || [];
    const w = list.reduce((a, s) => a + (s.w || 1), 0);
    const m = w ? list.reduce((a, s) => a + (s.w || 1) * (s.dur || 1), 0) / w : 1;
    return (_scenMeanCache[type.id] = m || 1);
}

/** 場面を1つ選ぶ (起きた場所と時刻に合うものから、重みつきで) */
function pickIncidentScenario(type, ctx) {
    const list = (INCIDENT_SCENARIOS[type.id] || []).filter(s => !s.where || s.where(ctx));
    if (!list.length) return null;
    const total = list.reduce((a, s) => a + (s.w || 1), 0);
    let r = Math.random() * total;
    for (const s of list) { r -= (s.w || 1); if (r < 0) return s; }
    return list[list.length - 1];
}

/**
 * 種類の定義に場面を重ねた「その回の輸送障害の定義」を作る。
 * 種類そのもの (INCIDENT_TYPES) は書き換えない。
 * 名前・id・系統は種類のまま (記録・割合の集計が変わらない)。
 */
function applyIncidentScenario(type, sc) {
    if (!sc) return type;
    const eff = Object.assign({}, type);
    ["causeText", "stock", "first", "crew", "phases", "slow", "after", "depts"].forEach(k => {
        if (sc[k] !== undefined) eff[k] = sc[k];
    });
    if (sc.addCrew) eff.crew = (eff.crew || []).concat(sc.addCrew).sort((a, b) => a[0] - b[0]);
    if (sc.block) eff.block = Object.assign({}, eff.block || {}, sc.block);
    if (sc.radius && eff.block) eff.block = Object.assign({}, eff.block, { radius: Math.max(1, eff.block.radius + sc.radius) });
    /* 時間の倍率は、その種類の場面の平均 (重みつき) で割って使う。
       場面ごとに重い・軽いはあっても、種類として平均すれば以前と同じ長さになる
       (輸送障害全体の重さの釣り合いを変えない)。 */
    const k = (sc.dur || 1) / incidentScenarioMeanDur(type);
    const scale = (r) => r ? [r[0] * k, r[1] * k] : r;
    eff.hold = scale(eff.hold);
    eff.suspend = scale(eff.suspend);
    eff.scenario = sc.label;
    eff.base = type;
    return eff;
}
