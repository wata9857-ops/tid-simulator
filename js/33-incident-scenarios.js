/** 場所の区分 (場面を選ぶための手がかり) */
function incidentScenarioCtx(game, trackId, index) {
    const blks = game.trackMgr.blocks[trackId] || [];
    const b = blks[index];
    const stIdx = (b && b.stationIdx !== undefined) ? b.stationIdx : Math.floor(index / UNITS_PER_STATION);
    const line = /^Kosei/.test(trackId) ? "kosei" : /^Fukuchi/.test(trackId) ? "fukuchi"
               : /^Tozai/.test(trackId) ? "tozai" : /^Ako/.test(trackId) ? "ako"
               : /Hoppo/.test(trackId) ? "hoppo" : "main";
    // 郊外 (山あい・田園) … 湖西線・赤穂線・JR宝塚線の宝塚より先・学研都市線の長尾より先・姫路より西・野洲より東
    const rural = line === "kosei" || line === "ako" ||
        (line === "fukuchi" && stIdx <= STATION_MAP["宝塚"]) ||
        (line === "tozai" && stIdx >= STATION_MAP["長尾"]) ||
        (line === "main" && (stIdx < STATION_MAP["姫路"] || stIdx > STATION_MAP["野洲"]));
    const h = (game.currentTime / 3600) % 24;
    return {
        line: line, rural: rural, urban: !rural,
        station: !!(b && isRealStationBlock(b)), stName: b ? blockStationName(b) : "",
        tunnelish: line === "tozai" && stIdx <= STATION_MAP["京橋"],   // JR東西線の地下区間
        hour: h, rush: (h >= 7 && h < 9.5) || (h >= 17 && h < 19.5), night: (h >= 21 || h < 5.5)
    };
}

